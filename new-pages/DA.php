	  <u><font size=+2><span style="font-style: normal; font-weight: 700">Uncertainty Quantification, Data Assimilation, and Sensitivity Analysis</span></font></u>
	  </p>
	  
<p><u>Uncertainty quantification</u> [as defined by SIAG in UQ] focuses on quantifying the uncertainty in output from large computational simulations, typically governed by partial differential equations, given uncertainties in parameters, data, and the model itself.</p>
<p><u>Data assimilation</u> is the process by which measurements and model predictions are 
  combined to obtain an accurate representation of the state of the modeled 
  system. Data assimilation is recognized as essential in weather, climate 
  analysis, and forecast activities. </p>
