    <u><font size=+2><span style="font-style: normal; font-weight: 700">Research Interests</span></font></u>
    </p>
     <p> My research interests reside in the areas of <strong>scientific computing</strong> and <strong>applied mathematics</strong>. My research focus is on the theory and application of algorithms  for modeling and simulation of <strong>real processes</strong>. Accurate numerical simulations are <strong>essential</strong> in understanding nature's mechanisms and predicting its behavior. Two <strong>fundamental aspects</strong> are necessary for accurate simulations: (1) accurate numerical algorithms and (2) knowledge of the true modeled system such as initial conditions and uncertain parameters. I am developing <a href="TimeStepping.php">robust time-stepping algorithms</a> and <a href="AMR.php">adaptive mesh refinement</a> techniques to efficiently evolve in time dynamical systems with multiple scales and physics. In order to address the second point, I am developing techniques aimed at <a href="DA.php">uncertainty quantification and reduction</a>. For a detailed description of my <a href="research.php">research interests</a> follow the section below for more information on specific topics.</p>
     <p>I started using Python in all my high level activities. One reson is well articulated in this <a href="http://www.r-bloggers.com/the-homogenization-of-scientific-computing-or-why-python-is-steadily-eating-other-languages-lunch/">blog post</a>.</p>
